const DICT: Record<Lang, Record<UiKey, string>> = { es, en };

/** Sustituye {marcadores} en un texto. */
export const fill = (s: string, vars: Record<string, string | number>) => s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''));

/** Idioma, textos y rutas de la página actual. Uso: const { lang, t, P } = useT(Astro.url); */
export function useT(url: URL) {
  const lang = langFromPath(url.pathname);
  const t = (key: UiKey, vars?: Record<string, string | number>) => (vars ? fill(DICT[lang][key], vars) : DICT[lang][key]);
  return { lang, t, P: PATHS[lang], locale: lang === 'en' ? 'en-US' : 'es-ES' };
}
